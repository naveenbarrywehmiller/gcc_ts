const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'timesheet-factory-'));
process.env.BOOTSTRAP_ADMIN_EMAIL = '';
process.env.BOOTSTRAP_ADMIN_PASSWORD = '';
process.env.MAINTENANCE_FILE = path.join(temporary, '.maintenance');
const config = require('../server/src/config/env');
config.dbPath = path.join(temporary, 'timesheet.db');
const db = require('../server/src/config/db');
const Database = require('../server/node_modules/better-sqlite3');
const bcrypt = require('../server/node_modules/bcryptjs');
const { migrate } = require('../server/src/config/migrate');
const { bootstrapAdmin, FACTORY_EMAIL, FACTORY_PASSWORD } = require('../server/src/config/bootstrapAdmin');
const { factoryReset } = require('../server/src/config/factoryReset');
const catalogs = ['platforms', 'divisions', 'projects', 'tasks', 'departments', 'supporting_categories', 'activities', 'subdivisions', 'holidays', 'timesheets', 'audit_logs'];
const backups = [];
after(() => {
  db._close();
  for (const file of backups) fs.rmSync(file, { force: true });
  fs.rmSync(temporary, { recursive: true, force: true });
});

test('fresh setup has only the factory System Admin and never repopulates test catalogs', () => {
  migrate({ bootstrap: false });
  bootstrapAdmin(db, {});
  require('../server/src/config/seed')();
  for (const table of catalogs) assert.equal(db.prepare(`SELECT COUNT(*) AS n FROM ${table}`).get().n, 0, table);
  const user = db.prepare('SELECT * FROM users').get();
  assert.equal(user.email, FACTORY_EMAIL);
  assert.equal(user.role, 'system admin');
  assert(bcrypt.compareSync(FACTORY_PASSWORD, user.password_hash));
  db.prepare('UPDATE users SET password_hash=?').run('changed');
  bootstrapAdmin(db, {});
  assert.equal(db.prepare('SELECT password_hash FROM users').get().password_hash, 'changed');
});

test('reset requires confirmation and a successful safety backup; reset never reuses old user IDs', async t => {
  const platform = db.prepare("INSERT INTO platforms(name) VALUES ('Trial')").run().lastInsertRowid;
  db.prepare("INSERT INTO divisions(name,platform_id) VALUES ('Trial',?)").run(platform);
  db.exec("INSERT INTO users(id,name,email,password_hash,role) VALUES(20,'Trial','trial@test.invalid','unused','employee'); INSERT INTO audit_logs(user_id,action) VALUES(20,'TEST')");
  await assert.rejects(factoryReset(false), /--confirm/);
  const instance = db._instance;
  const mock = t.mock.method(instance, 'backup', async () => { throw new Error('disk full'); });
  await assert.rejects(factoryReset(true), /disk full/);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM users').get().n, 2);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM platforms').get().n, 1);
  mock.mock.restore();
  const backup = await factoryReset(true);
  backups.push(backup);
  const saved = new Database(backup, { readonly: true });
  assert.equal(saved.prepare('SELECT COUNT(*) AS n FROM users').get().n, 2);
  saved.close();
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM users').get().n, 1);
  const user = db.prepare('SELECT * FROM users').get();
  assert(user.id > 20, 'former JWT user IDs cannot become the factory admin');
  assert.equal(user.email, FACTORY_EMAIL);
  assert(bcrypt.compareSync(FACTORY_PASSWORD, user.password_hash));
  for (const table of catalogs) assert.equal(db.prepare(`SELECT COUNT(*) AS n FROM ${table}`).get().n, 0, table);
  migrate();
  for (const table of catalogs) assert.equal(db.prepare(`SELECT COUNT(*) AS n FROM ${table}`).get().n, 0, table);
  assert(fs.existsSync(process.env.MAINTENANCE_FILE));
  assert.deepEqual(db.pragma('foreign_key_check'), []);
});

test('classification upgrade preserves relationships, sequences, indexes and triggers', () => {
  const legacy = new Database(':memory:');
  legacy.pragma('foreign_keys=ON');
  legacy.exec(`CREATE TABLE projects(id INTEGER PRIMARY KEY AUTOINCREMENT, project_code TEXT UNIQUE, billing_type TEXT CHECK(billing_type IN ('Billable','Non-Billable')));
    CREATE TABLE tasks(id INTEGER PRIMARY KEY, classification TEXT);
    CREATE TABLE project_tasks(project_id INTEGER REFERENCES projects(id), task_id INTEGER REFERENCES tasks(id));
    CREATE INDEX project_code_index ON projects(project_code);
    CREATE TRIGGER preserve_project_code BEFORE UPDATE OF project_code ON projects WHEN NEW.project_code='' BEGIN SELECT RAISE(ABORT,'Required'); END;
    INSERT INTO projects VALUES(7,'OLD','Billable'),(8,'OLD2','Non-Billable');
    INSERT INTO tasks VALUES(3,'Billable'),(4,'Non-Billable');
    INSERT INTO project_tasks VALUES(7,3),(8,4);
    UPDATE sqlite_sequence SET seq=30 WHERE name='projects';`);
  const upgrade = require('../server/src/config/classificationMigration');
  upgrade(legacy); upgrade(legacy);
  assert.deepEqual(legacy.prepare('SELECT billing_type FROM projects ORDER BY id').all(), [{ billing_type: 'Productive' }, { billing_type: 'Non-Productive' }]);
  assert.deepEqual(legacy.prepare('SELECT classification FROM tasks ORDER BY id').all(), [{ classification: 'Productive' }, { classification: 'Non-Productive' }]);
  assert.equal(legacy.prepare('SELECT COUNT(*) AS n FROM project_tasks').get().n, 2);
  assert.deepEqual(legacy.pragma('foreign_key_check'), []);
  assert.equal(legacy.prepare("INSERT INTO projects(project_code,billing_type) VALUES ('NEW','Productive')").run().lastInsertRowid, 31);
  assert.throws(() => legacy.exec("UPDATE projects SET project_code='' WHERE id=7"), /Required/);
  assert(legacy.prepare("SELECT 1 FROM sqlite_master WHERE name='project_code_index'").get());
  assert.equal(legacy.pragma('foreign_keys', { simple: true }), 1);
  legacy.close();
});

test('manual database backup/restore keep maintenance enabled and save recovery data', async () => {
  const { backupDatabase } = require('../server/src/config/backup');
  const { restoreDatabase } = require('../server/src/config/restore');
  const backup = await backupDatabase();
  backups.push(backup);
  assert(fs.existsSync(process.env.MAINTENANCE_FILE));
  assert(!fs.existsSync(process.env.MAINTENANCE_FILE + '-operation'));
  db.prepare("INSERT INTO platforms(name) VALUES ('After backup')").run();
  await assert.rejects(restoreDatabase(backup, false), /--confirm/);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM platforms').get().n, 1);
  const safety = await restoreDatabase(backup, true);
  backups.push(safety);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM platforms').get().n, 0);
  const previous = new Database(safety, { readonly: true });
  assert.equal(previous.prepare('SELECT COUNT(*) AS n FROM platforms').get().n, 1);
  previous.close();
  assert(fs.existsSync(process.env.MAINTENANCE_FILE));
  assert(!fs.existsSync(process.env.MAINTENANCE_FILE + '-operation'));
});
